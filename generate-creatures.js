// Bakes creatures.js from PokéAPI for Gen 1+2 (dex 1..251). Run once: node generate-creatures.js
// Output committed to repo so the app doesn't need runtime API calls.
const MAX_ID = 251;
const A = 'https://pokeapi.co/api/v2';

async function batch(ids, fn, size = 25) {
  const out = [];
  for (let i = 0; i < ids.length; i += size) {
    out.push(...await Promise.all(ids.slice(i, i + size).map(fn)));
    process.stderr.write(`\r${out.length}/${ids.length}`);
  }
  process.stderr.write('\n');
  return out;
}
const get = async (url) => (await fetch(url)).json();
const cap = s => s.replace(/(^|[\s-])\w/g, c => c.toUpperCase());
const enName = (sp) => (sp.names.find(n => n.language.name === 'en') || {}).name || cap(sp.name);

const ids = Array.from({ length: MAX_ID }, (_, i) => i + 1);
const [species, pokemon] = await Promise.all([
  batch(ids, id => get(`${A}/pokemon-species/${id}/`)),
  batch(ids, id => get(`${A}/pokemon/${id}/`)),
]);

const from = {}; // evolves_from lookup
for (const sp of species) from[sp.name] = sp.evolves_from_species?.name || null;

const list = [];
for (let i = 0; i < MAX_ID; i++) {
  const sp = species[i], pk = pokemon[i];
  if (sp.id !== i + 1) throw new Error(`dex misalignment at ${i + 1}`);
  // one forward link: first species in range that evolves from this one (deterministic by dex #)
  const evo = species.find(s2 => from[s2.name] === sp.name && s2.id <= MAX_ID);
  const legendary = sp.is_legendary || sp.is_mythical;
  const be = pk.base_experience ?? 100;
  const rarity = legendary ? 3 : be < 80 ? 1 : be < 150 ? 2 : 3;
  const c = {
    id: sp.name,
    pid: sp.id,
    name: enName(sp),
    types: pk.types.map(t => cap(t.type.name)),
    rarity,
    ...(!legendary && evo ? { evolvesTo: evo.name } : {}),
    ...(legendary ? { req: { minStreak: 7, minSessions: 100 } } : {}),
  };
  list.push(c);
}
console.error(`creatures: ${list.length}, evolutions: ${list.filter(c => c.evolvesTo).length}, gated: ${list.filter(c => c.req).length}`);

const out = `// GENERATED by generate-creatures.js from PokéAPI (Gen 1+2). Do not hand-edit.
const CREATURES = ${JSON.stringify(list, null, 1)};
`;
await import('fs').then(fs => fs.writeFileSync('creatures.js', out));
console.log(`wrote creatures.js (${out.length} bytes)`);
